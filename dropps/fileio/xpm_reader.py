import numpy as np


def _xpm_comment_text(value):
    return str(value).replace("*/", "* /").replace("\n", " ")


def _xpm_quoted_text(value):
    return _xpm_comment_text(value).replace("\\", "\\\\").replace('"', '\\"')


def write_discrete_xpm(
    array,
    filename,
    *,
    colors,
    labels=None,
    title="Secondary structure",
    legend="Secondary structure",
    xlabel="Time (ns)",
    ylabel="Residue",
    x_axis=None,
    y_axis=None,
):
    """Write a GROMACS-compatible discrete XPM matrix.

    ``array`` is supplied in ordinary matrix order ``(y, x)``.  GROMACS XPM
    stores the highest/last y row first, so rows are reversed only while
    writing.  State values and color-map keys must be one printable character.
    """

    values = np.asarray(array)
    if values.ndim != 2 or values.size == 0:
        raise ValueError("Discrete XPM input must be a non-empty 2D array.")
    values = values.astype(str)
    unique_values = set(np.unique(values).tolist())
    color_keys = set(colors)
    missing = sorted(unique_values - color_keys)
    if missing:
        raise ValueError(f"Discrete XPM colors are missing states: {missing}.")
    for key, color in colors.items():
        if len(str(key)) != 1 or str(key) in {'"', "\\"}:
            raise ValueError("Discrete XPM state keys must be safe single characters.")
        color_text = str(color)
        if not color_text.startswith("#") or len(color_text) != 7:
            raise ValueError("Discrete XPM colors must use #RRGGBB notation.")

    labels = {} if labels is None else dict(labels)
    height, width = values.shape
    if x_axis is not None:
        x_axis = np.asarray(x_axis)
        if x_axis.shape != (width,) or not np.all(np.isfinite(x_axis.astype(float))):
            raise ValueError("Discrete XPM x-axis must contain one finite value per column.")
    if y_axis is not None:
        y_axis = np.asarray(y_axis)
        if y_axis.shape != (height,) or not np.all(np.isfinite(y_axis.astype(float))):
            raise ValueError("Discrete XPM y-axis must contain one finite value per row.")

    ordered_keys = [str(key) for key in colors if str(key) in unique_values]
    with open(filename, "w", encoding="utf-8") as handle:
        handle.write("/* XPM */\n")
        handle.write("/* This matrix is generated by DROPPS. */\n")
        handle.write(f'/* title:   "{_xpm_quoted_text(title)}" */\n')
        handle.write(f'/* legend:  "{_xpm_quoted_text(legend)}" */\n')
        handle.write(f'/* x-label: "{_xpm_quoted_text(xlabel)}" */\n')
        handle.write(f'/* y-label: "{_xpm_quoted_text(ylabel)}" */\n')
        handle.write('/* type:    "Discrete" */\n')
        handle.write("static char * gv_xpm[] = {\n")
        handle.write(f'"{width} {height} {len(ordered_keys)} 1",\n')
        for key in ordered_keys:
            label = _xpm_quoted_text(labels.get(key, key))
            handle.write(f'"{key} c {colors[key]}" /* "{label}" */,\n')
        if x_axis is not None:
            ticks = " ".join(f"{float(value):.12g}" for value in x_axis)
            handle.write(f"/* x-axis:  {ticks} */\n")
        if y_axis is not None:
            ticks = " ".join(f"{float(value):.12g}" for value in y_axis)
            handle.write(f"/* y-axis:  {ticks} */\n")
        reversed_rows = values[::-1]
        for row_index, row in enumerate(reversed_rows):
            line = "".join(row.tolist())
            suffix = "," if row_index < height - 1 else ""
            handle.write(f'"{line}"{suffix}\n')
        handle.write("};\n")

def write_xpm(array: np.ndarray, filename: str, title: str = "XPM Image"):
    array = np.asarray(array, dtype=float)
    if array.ndim != 2 or array.size == 0:
        raise ValueError("XPM input must be a non-empty two-dimensional array.")
    if not np.all(np.isfinite(array)):
        raise ValueError("XPM input contains NaN or infinite values.")

    height, width = array.shape
    palette = "0123456789ABCDEFGHIJKLMNOPQRSTUVWXYZabcdefghijklmnopqrstuvwxyz+-"
    color_count = len(palette)

    minimum = float(np.min(array))
    maximum = float(np.max(array))
    if maximum == minimum:
        fill_index = color_count - 1 if maximum != 0 else 0
        color_indices = np.full(array.shape, fill_index, dtype=int)
    else:
        normalized = (array - minimum) / (maximum - minimum)
        color_indices = np.rint(normalized * (color_count - 1)).astype(int)

    with open(filename, 'w') as f:
        safe_title = title.replace("*/", "* /")
        f.write('/* XPM */\n')
        f.write(f'/* {safe_title} */\n')
        f.write('static char * xpm_data[] = {\n')
        f.write(f'"{width} {height} {color_count} 1",\n')

        for index, char in enumerate(palette):
            shade = 255 - round(255 * index / (color_count - 1))
            f.write(f'"{char} c #{shade:02X}{shade:02X}{shade:02X}",\n')

        for row_index, row in enumerate(color_indices):
            line = ''.join(palette[index] for index in row)
            suffix = ',' if row_index < height - 1 else ''
            f.write(f'"{line}"{suffix}\n')

        f.write('};\n')
